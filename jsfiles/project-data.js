// ========================================
// REUSABLE PROJECT DETAILS PAGE
// ========================================

document.addEventListener("DOMContentLoaded", () => {

    // Get the selected project ID from the URL
    const params = new URLSearchParams(window.location.search);
    const projectId = params.get("id") || "solar";

    // Find the selected project's data
    const project = projects[projectId];

    // Handle invalid project IDs
    if (!project) {
        document.querySelector("main").innerHTML = `
            <section class="project-overview-section">
                <div class="project-detail-container">
                    <h1>Project Not Found</h1>
                    <p>
                        Sorry, this project could not be found.
                        Please return to our projects section.
                    </p>
                    <a href="../index.html#projects">
                        Back to Projects
                    </a>
                </div>
            </section>
        `;

        document.title = "Project Not Found | Zirkbe Synergy Limited";
        return;
    }

    // Update browser title and meta description
    document.title =
        `${project.title} | Zirkbe Synergy Limited`;

    const metaDescription = document.getElementById(
        "projectMetaDescription"
    );

    if (metaDescription) {
        metaDescription.content = project.intro;
    }

    // Update project breadcrumb
    document.getElementById("projectBreadcrumb").textContent =
        `Home / Projects / ${project.title}`;

    // Update project category
    document.getElementById("projectCategoryLabel").textContent =
        project.categoryLabel;

    // Update project title
    const titleElement = document.getElementById("projectTitle");
    titleElement.childNodes[0].nodeValue =
        `${project.titleFirst} `;

    titleElement.querySelector("span").textContent =
        project.titleSecond;

    // Update project introduction
    document.getElementById("projectIntro").textContent =
        project.intro;

    // Update project metadata
    document.getElementById("projectLocation").textContent =
        project.location;

    document.getElementById("projectCategory").textContent =
        project.category;

    document.getElementById("projectYear").textContent =
        project.year;

    // Update project image
    const projectImage = document.getElementById("projectImage");

    projectImage.src = project.image;
    projectImage.alt = project.imageAlt;

    // Update overview heading
    const overviewHeading = document.getElementById(
        "projectOverviewHeading"
    );

    overviewHeading.childNodes[0].nodeValue =
        `${project.overviewHeadingFirst} `;

    overviewHeading.querySelector("span").textContent =
        project.overviewHeadingSecond;

    // Update overview paragraphs
    project.overview.forEach((paragraph, index) => {
        const element = document.getElementById(
            `projectOverview${index + 1}`
        );

        if (element) {
            element.textContent = paragraph;
        }
    });

    // Update scope heading
    const scopeHeading = document.getElementById(
        "projectScopeHeading"
    );

    scopeHeading.childNodes[0].nodeValue =
        `${project.scopeHeadingFirst} `;

    scopeHeading.querySelector("span").textContent =
        project.scopeHeadingSecond;

    // Generate project scope cards
    const scopeGrid = document.getElementById("projectScopeGrid");

    scopeGrid.replaceChildren();

    project.scope.forEach((item, index) => {

        const card = document.createElement("article");
        card.className = "project-scope-card";

        const number = document.createElement("span");
        number.className = "scope-number";
        number.textContent = String(index + 1).padStart(2, "0");

        const heading = document.createElement("h3");
        heading.textContent = item.title;

        const description = document.createElement("p");
        description.textContent = item.description;

        card.append(number, heading, description);
        scopeGrid.appendChild(card);
    });

});